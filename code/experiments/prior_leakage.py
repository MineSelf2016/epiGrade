from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import numpy as np
import torch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from epigrade.config import load_config
from epigrade.data import load_h5ad_dataset, prepare_fold_data
from epigrade.metrics import protein_pearson_mean
from epigrade.training import retrieve_training_priors, set_seed, train_alignment
from run_fused import new_aligner, retrieve


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT.parent / "data/processed/cbmc.h5ad")
    parser.add_argument("--splits", type=Path,
                        default=ROOT.parent / "results_epigrade/CBMC_cell_full/splits.json")
    parser.add_argument("--out", type=Path, default=ROOT.parent / "results_fused/prior_leakage.json")
    parser.add_argument("--sections", type=Path, default=ROOT.parent / "paper/sections")
    parser.add_argument("--config", type=Path, default=ROOT / "configs" / "fused.yaml")
    args = parser.parse_args()
    config = load_config(args.config)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dataset = load_h5ad_dataset(args.data, config.experiment.protein_obsm_key)
    rows = []
    for fold_id, split in enumerate(json.loads(args.splits.read_text())):
        set_seed(config.experiment.seed + fold_id)
        fit, validation = (np.asarray(split[k], np.int64) for k in ("fit", "validation"))
        prepared = prepare_fold_data(
            dataset, fit, config.preprocessing.normalization_target_sum,
            config.preprocessing.genes_per_protein, config.preprocessing.gene_cap)
        rna, protein = prepared.rna_normalized, prepared.protein_normalized
        aligner = new_aligner(rna.shape[1], protein.shape[1], config, device)
        train_alignment(aligner, rna[fit], prepared.rna_counts[fit], protein[fit],
                        prepared.protein_counts[fit], config, device, log=lambda s: None)
        in_sample = retrieve_training_priors(aligner, rna[fit], protein[fit], config, device)
        held_out = retrieve(aligner, rna, protein, fit, validation, config, device)
        rows.append({"fold": fold_id,
                     "fit_in_sample": protein_pearson_mean(in_sample.protein_prior, protein[fit]),
                     "validation": protein_pearson_mean(held_out.protein_prior,
                                                        protein[validation])})
        print(rows[-1], flush=True)
    args.out.write_text(json.dumps(rows, indent=2))
    mean = lambda key: float(np.mean([r[key] for r in rows]))
    args.sections.joinpath("numbers_leakage.tex").write_text(
        "% generated by prior_leakage.py -- do not edit\n"
        f"\\newcommand{{\\numPriorFitInSample}}{{{mean('fit_in_sample'):.3f}}}\n"
        f"\\newcommand{{\\numPriorFitValidation}}{{{mean('validation'):.3f}}}\n")


if __name__ == "__main__":
    main()
