from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys
import time

import anndata as ad
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from epigrade.panels import canonicalise_panel, is_control

RUN_LABEL = {"CBMC": "CBMC", "ECCITE": "PBMC 5$'$", "GSE3P": "PBMC 3$'$"}

DATASETS = {
    "CBMC": ("cbmc.h5ad", "GSE100866", "CITE-seq, cord blood"),
    "PBMC 5$'$": ("eccite_5p.h5ad", "GSE164378", "CITE-seq, PBMC 5$'$"),
    "PBMC 3$'$": ("gse3p_3p.h5ad", "GSE164378", "CITE-seq, PBMC 3$'$"),
    "COVID-19 PBMC": ("covid_pbmc.h5ad", "GSE155673", "CITE-seq, acute COVID-19"),
    "Bone marrow": ("bonemarrow.h5ad", "GSE128639", "CITE-seq, bone marrow MNC"),
}


def _panels(processed: Path) -> dict[str, list[str]]:
    panels = {}
    for label, (filename, _, _) in DATASETS.items():
        path = processed / filename
        if not path.exists():
            continue
        adata = ad.read_h5ad(path, backed="r")
        panels[label] = list(map(str, adata.uns["raw_protein_names"]))
    return panels


def write_harmonisation_macros(processed: Path, out: Path) -> None:
    from epigrade.config import load_config
    from epigrade.data import load_h5ad_dataset

    config = load_config(ROOT / "configs" / "epigrade.yaml")
    worst, names = 0.0, []
    for label, (filename, _, _) in DATASETS.items():
        path = processed / filename
        if not path.exists():
            continue
        dataset = load_h5ad_dataset(path, config.experiment.protein_obsm_key)
        values = np.asarray(dataset.protein_counts)
        fraction = float(np.mean(~np.isclose(values, np.round(values))))
        if fraction > 0:
            names.append(label)
            worst = max(worst, fraction)
    out.write_text(
        "% generated by make_supplementary.py -- do not edit\n"
        f"\\newcommand{{\\numNonIntegerShare}}{{{100 * worst:.1f}\\%}}\n"
        f"\\newcommand{{\\numNonIntegerPanels}}{{{len(names)}}}\n"
        + _totalvi_fidelity_macro(),
        encoding="utf-8")
    print("harmonisation macros written to", out)


def write_annotation_macros(results: Path, out: Path) -> None:
    blocks = {}
    for path in sorted(results.glob("*_annotation/annotation_summary.json")):
        blocks[path.parent.name.replace("_annotation", "")] = \
            json.loads(path.read_text())["results"]
    if not blocks:
        out.write_text("% no annotation runs yet\n", encoding="utf-8")
        return
    spelled = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
               "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    lines = []
    for key, block in blocks.items():
        dataset, _, split = key.partition("_")
        stem = ("Wide" if dataset == "GSE3P" else "Narrow") + split.capitalize()
        for method, tag in (("EpiGrade", "Imputed"), ("measured_protein", "Measured"),
                            ("rna_only", "Rna"), ("retrieval_prior", "Prior")):
            entry = block.get(method)
            if entry is None:
                continue
            name = f"numAnnot{tag}{stem}".translate(str.maketrans(spelled))
            lines.append(f"\\newcommand{{\\{name}}}{{{entry['macro_f1']:.3f}}}")
    out.write_text("% generated by make_supplementary.py -- do not edit\n"
                   + "\n".join(sorted(lines)) + "\n", encoding="utf-8")
    print("annotation macros written to", out)


def _totalvi_fidelity_macro(results: Path | None = None) -> str:
    directory = results or (ROOT.parent / "results_fused")
    values = []
    for path in sorted(directory.glob("*_external/baseline_summary.json")):
        block = json.loads(path.read_text())["methods"].get("totalvi")
        if not block:
            continue
        values += [f["training_reconstruction_pcc_p"] for f in block["folds"]
                   if "training_reconstruction_pcc_p" in f]
    if not values:
        return ""
    return f"\\newcommand{{\\numTotalVIFidelity}}{{{min(values):.2f}}}\n"


def write_panel_table(processed: Path, out: Path) -> None:
    panels = _panels(processed)
    if not panels:
        out.write_text("% no processed data yet\n", encoding="utf-8")
        return
    canon = {label: canonicalise_panel(panel)[1] for label, panel in panels.items()}
    labels = list(panels)

    lines = [
        "% generated by make_supplementary.py -- do not edit",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{Antibody panel harmonisation. Raw features are mapped to "
        "canonical protein symbols by stripping clone and chemistry suffixes, "
        "resolving an alias table and preferring an explicit CD number; isotype "
        "and hashing controls are removed, and replicate antibodies mapping to "
        "the same symbol are averaged. The lower block gives the number of "
        "canonical symbols shared by each pair of studies, which determines the "
        "available protein overlap for cross-cohort evaluation.}",
        "\\label{tab:supp-panels}",
        "\\begin{tabular}{lrrr}", "\\toprule",
        "Dataset & Raw features & Canonical symbols & Controls removed \\\\",
        "\\midrule",
    ]
    for label in labels:
        dropped = sum(1 for feature in panels[label] if is_control(feature))
        lines.append(f"{label} & {len(panels[label])} & {len(canon[label])} & {dropped} \\\\")
    lines += ["\\midrule",
              "\\multicolumn{4}{l}{\\textit{Shared canonical symbols between studies}} \\\\"]
    for i, a in enumerate(labels):
        for b in labels[i + 1:]:
            shared = len(set(canon[a]) & set(canon[b]))
            lines.append(f"\\multicolumn{{3}}{{l}}{{\\quad {a} $\\cap$ {b}}} & {shared} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def write_dataset_table(processed: Path, out: Path) -> None:
    rows = []
    for label, (filename, accession, assay) in DATASETS.items():
        path = processed / filename
        if not path.exists():
            continue
        adata = ad.read_h5ad(path, backed="r")
        protein = adata.obsm["protein_expression"]
        counts = {}
        for key in ("donor", "batch", "time", "celltype_l1"):
            counts[key] = adata.obs[key].astype(str).nunique() if key in adata.obs else None
        rows.append({
            "label": label, "accession": accession, "assay": assay,
            "cells": adata.n_obs, "genes": adata.n_vars,
            "proteins": protein.shape[1], **counts,
        })
    if not rows:
        out.write_text("% no processed data yet\n", encoding="utf-8")
        return

    lines = [
        "% generated by make_supplementary.py -- do not edit",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{Datasets after preparation. Protein counts are the harmonised "
        "panels of Supplementary Table~\\ref{tab:supp-panels}. Donor counts indicate "
        "the availability of grouped evaluation; CBMC is a single pooled "
        "sample and is evaluated only with cell-level splitting.}",
        "\\label{tab:supp-datasets}",
        "\\begin{tabular}{llrrrrrr}", "\\toprule",
        "Dataset & Accession & Cells & Genes & Proteins & Donors & Batches & "
        "Cell types \\\\", "\\midrule",
    ]
    for row in rows:
        fmt = lambda v: "--" if v is None else str(v)
        lines.append(
            f"{row['label']} & {row['accession']} & {row['cells']:,} & "
            f"{row['genes']:,} & {row['proteins']} & {fmt(row['donor'])} & "
            f"{fmt(row['batch'])} & {fmt(row['celltype_l1'])} \\\\".replace(",", "\\,"))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def write_drift_table(results: Path, out: Path) -> None:
    rows = []
    for summary_path in sorted(results.glob("*/summary.json")):
        if summary_path.parent.name.startswith("xc_"):
            continue
        summary = json.loads(summary_path.read_text())
        if summary.get("variant") != "full":
            continue
        drifts = [f.get("geometry_drift") for f in summary.get("folds", [])]
        drifts = [d for d in drifts if d]
        if not drifts:
            continue
        jaccard = [d["neighbour_jaccard_start_to_end"] for d in drifts
                   if d.get("neighbour_jaccard_start_to_end") is not None]
        rows.append({
            "dataset": summary["dataset"], "split": summary["split_mode"],
            "jaccard": float(np.mean(jaccard)) if jaccard else None,
            "shift": float(np.mean([d["mean_prior_shift_l2"] for d in drifts])),
        })
    if not rows:
        out.write_text("% no completed full-model runs yet\n", encoding="utf-8")
        return

    lines = [
        "% generated by make_supplementary.py -- do not edit",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Retrieval-geometry drift during the correction stage. The RNA "
        "encoder keeps being updated while the corrector trains, so neighbour "
        "sets retrieved at the start of the stage are not the ones the model is "
        "applied to at test time. The Jaccard column gives the mean overlap "
        "between the first and last neighbour sets of a training cell; the shift "
        "column is the mean $\\ell_2$ displacement of the resulting prior. "
        "Refreshing the training sources every 10 epochs removes this mismatch.}",
        "\\label{tab:supp-drift}",
        "\\begin{tabular}{llcc}", "\\toprule",
        "Dataset & Protocol & Neighbour Jaccard & Prior shift ($\\ell_2$) \\\\",
        "\\midrule",
    ]
    for row in rows:
        jaccard = "--" if row["jaccard"] is None else f"{row['jaccard']:.3f}"
        name = RUN_LABEL.get(row["dataset"], row["dataset"])
        lines.append(f"{name} & {row['split']} & {jaccard} & "
                     f"{row['shift']:.3f} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def write_annotation_table(results: Path, out: Path) -> None:
    import json as _json
    blocks = {}
    for path in sorted(results.glob("*_annotation/annotation_summary.json")):
        block = _json.loads(path.read_text())
        blocks[path.parent.name.replace("_annotation", "")] = block
    if not blocks:
        out.write_text("% no annotation runs yet\n", encoding="utf-8")
        return

    label = {"measured_protein": "Measured protein (ceiling)",
             "EpiGrade": "Imputed protein (\\textsc{EpiGrade})",
             "retrieval_prior": "Imputed protein (prior only)",
             "rna_only": "Transcriptome only (50 PCs)"}
    keys = sorted(blocks)
    lines = [
        "% generated by make_supplementary.py -- do not edit",
        "\\begin{table*}[t]", "\\centering",
        '\\caption{Cell-type annotation using measured protein, imputed protein and transcriptome representations. A linear classifier is evaluated against the source study annotations using donor-grouped folds. Values are mean macro-F1 with standard deviations across folds. Higher classification performance from imputed than measured protein may reflect smoothing and does not independently establish accurate reconstruction of protein abundance.}',
        "\\label{tab:supp-annotation}",
        "\\begin{tabular}{l" + "c" * len(keys) + "}", "\\toprule",
    ]
    header = "Features"
    for key in keys:
        dataset, _, split = key.partition("_")
        header += f" & {RUN_LABEL.get(dataset, dataset)}, {split}"
    lines += [header + " \\\\", "\\midrule"]
    for method, text in label.items():
        row = text
        for key in keys:
            entry = blocks[key]["results"].get(method)
            row += (f" & {entry['macro_f1']:.3f} $\\pm$ {entry['macro_f1_sd']:.3f}"
                    if entry else " & --")
        lines.append(row + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def write_timing_table(processed: Path, out: Path) -> None:
    import torch

    from epigrade.aligner import CrossModalAligner
    from epigrade.config import load_config
    from epigrade.fusion import TranscriptomeNetwork, apply_fusion
    from epigrade.training import build_memory, encode_rna
    from run_fused import load_fusion_settings

    config = load_config(ROOT / "configs" / "fused.yaml")
    settings = load_fusion_settings(ROOT / "configs" / "fused.yaml")
    rng = np.random.default_rng(0)
    n_query, n_genes, n_proteins = 5000, 1000, 100
    device = torch.device("cpu")

    aligner = CrossModalAligner(
        rna_dim=n_genes, protein_dim=n_proteins,
        hidden_dim=config.alignment.hidden_dim,
        latent_dim=config.alignment.latent_dim,
        projection_dim=config.alignment.projection_dim,
        depth=config.alignment.depth, dropout=config.alignment.dropout,
        temperature_init=config.alignment.temperature_init).to(device).eval()
    members = [TranscriptomeNetwork(n_genes, n_proteins, settings.hidden_dim,
                                    settings.dropout, len(settings.quantiles)
                                    ).to(device).eval()
               for _ in range(settings.members)]
    weights = rng.normal(size=(n_proteins, 3))

    def fused(genes: np.ndarray, prior: np.ndarray) -> np.ndarray:
        with torch.no_grad():
            x = torch.from_numpy(genes)
            mean = np.mean([m(x)[0].numpy() for m in members], axis=0)
        return apply_fusion(weights, [mean, prior])

    query_rna = rng.normal(size=(n_query, n_genes)).astype(np.float32)

    warm = encode_rna(aligner, query_rna[:256], device)
    fused(query_rna[:256], np.zeros((256, n_proteins), dtype=np.float32))
    warm_memory = build_memory(config)
    warm_memory.fit(rng.normal(size=(1000, config.alignment.latent_dim)).astype(np.float32),
                    rng.normal(size=(1000, n_proteins)).astype(np.float32))
    warm_memory.retrieve(warm[:16], config.retrieval.neighbors)
    del warm, warm_memory

    rows = []
    for atlas_size in (10_000, 50_000, 200_000):
        atlas_latent = rng.normal(
            size=(atlas_size, config.alignment.latent_dim)).astype(np.float32)
        atlas_protein = rng.normal(
            size=(atlas_size, n_proteins)).astype(np.float32)

        started = time.perf_counter()
        latent = encode_rna(aligner, query_rna, device)
        encode_ms = (time.perf_counter() - started) * 1000

        memory = build_memory(config)
        started = time.perf_counter()
        memory.fit(atlas_latent, atlas_protein)
        build_ms = (time.perf_counter() - started) * 1000

        started = time.perf_counter()
        retrieval = memory.retrieve(latent, config.retrieval.neighbors)
        search_ms = (time.perf_counter() - started) * 1000

        started = time.perf_counter()
        fused(query_rna, retrieval.protein_prior)
        field_ms = (time.perf_counter() - started) * 1000

        rows.append({"atlas": atlas_size, "encode": encode_ms, "build": build_ms,
                     "search": search_ms, "field": field_ms,
                     "total": encode_ms + search_ms + field_ms})

    lines = [
        "% generated by make_supplementary.py -- do not edit",
        "\\begin{table*}[t]", "\\centering",
        '\\caption{Inference time by component for 5000 query cells across reference atlas sizes, measured in milliseconds using a fixed set of CPU cores. Network time includes all five ensemble members and fusion. Exact inner-product search scales with atlas size. Index-construction time is reported separately as a one-time cost.}',
        "\\label{tab:supp-timing}",
        "\\begin{tabular}{rrrrrr}", "\\toprule",
        "Atlas cells & RNA encoding & Retrieval search & Network and fusion & "
        "Total & (Index build) \\\\", "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row['atlas']:,} & {row['encode']:.0f} & {row['search']:.0f} & "
            f"{row['field']:.0f} & {row['total']:.0f} & {row['build']:.0f} \\\\"
            .replace(",", "\\,"))
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--processed", type=Path, default=ROOT.parent / "data" / "processed")
    parser.add_argument("--results", type=Path, default=ROOT.parent / "results_fused")
    parser.add_argument("--sections", type=Path, default=ROOT.parent / "paper" / "sections")
    parser.add_argument("--skip-timing", action="store_true")
    args = parser.parse_args()
    args.sections.mkdir(parents=True, exist_ok=True)

    write_panel_table(args.processed, args.sections / "supp_panels.tex")
    write_harmonisation_macros(args.processed,
                               args.sections / "numbers_panels.tex")
    write_dataset_table(args.processed, args.sections / "supp_datasets.tex")
    write_annotation_table(args.results, args.sections / "supp_annotation.tex")
    write_annotation_macros(args.results, args.sections / "numbers_annotation.tex")
    if not args.skip_timing:
        write_timing_table(args.processed, args.sections / "supp_timing.tex")
    print("supplementary tables written to", args.sections)


if __name__ == "__main__":
    main()
